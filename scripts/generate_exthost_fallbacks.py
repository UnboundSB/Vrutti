#!/usr/bin/env python3
"""Generates the fallback table for the extension host contract.

The extension host calls the renderer through the `MainThread*` shapes of the
upstream protocol. Vrutti does not implement every one of those calls -- an
editor without a chat view cannot answer the chat calls, for instance. But an
unanswered call must never be an *error*: the extension host turns an error
reply into an `ExtensionHostError`, and an extension that sees one during its
activation gives up.

So every call that Vrutti does not implement is answered with the benign
default of its return type:

    Promise<void>                 -> null
    Promise<string>               -> ""
    Promise<number>               -> 0
    Promise<boolean>              -> false
    Promise<Some[]>               -> []
    Promise<Some | undefined>     -> null
    Promise<Some>                 -> null

The extension then sees a feature that is not there, instead of a failure it
cannot recover from.

This script reads the upstream protocol definition and writes the table as a
C++ header, so the C++ core does not need the upstream tree at compile time
and the table can never drift from the signatures it was derived from.

Usage:

    python scripts/generate_exthost_fallbacks.py [--check]
"""

from __future__ import annotations

import argparse
import pathlib
import re
import sys

REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent

PROTOCOL_CPP = REPO_ROOT / "src" / "core" / "ipc" / "VSCodeProtocol.cpp"
HEADER_PATH = REPO_ROOT / "src" / "core" / "ipc" / "VsCodeProxyFallbacks.generated.h"

UPSTREAM_PROTOCOL_CANDIDATES = [
    REPO_ROOT.parent / "src" / "vr" / "workbench" / "api" / "common" / "extHost.protocol.ts",
    REPO_ROOT.parent / "src" / "vs" / "workbench" / "api" / "common" / "extHost.protocol.ts",
]

# The kinds of answer the C++ side can build.
KINDS = {
    "Null": "nullptr",
    "EmptyString": '""',
    "Zero": "0",
    "False": "false",
    "EmptyArray": "[]",
}

HEADER_TEMPLATE = """//------------------------------------------------------------------------------
// <auto-generated>
//   Generated by scripts/generate_exthost_fallbacks.py -- DO NOT EDIT BY HAND.
//
//   Source of truth:
//     {source_rel}
//
//   The benign answer for every extension host call that Vrutti does not
//   implement. The extension host treats an error reply as a failure of the
//   extension, so a missing feature is answered with the empty value of the
//   declared return type instead.
//
//   Regenerate with:
//     python scripts/generate_exthost_fallbacks.py
// </auto-generated>
//------------------------------------------------------------------------------

#pragma once

namespace vrutti::core::ipc {{

// The kind of answer that is sent for a call without an implementation.
enum class FallbackKind {{
    Null,          // null
    EmptyString,   // ""
    Zero,          // 0
    False,         // false
    EmptyArray,    // []
}};

struct FallbackEntry {{
    const char* key;       // "Shape.$method"
    FallbackKind kind;
}};

// The table, sorted by key so it can be searched with a binary search.
inline constexpr FallbackEntry FALLBACKS[] = {{
{entries}
}};

inline constexpr int FALLBACK_COUNT = {count};

}} // namespace vrutti::core::ipc
"""


def match_braces(text: str, open_index: int) -> int:
    depth = 0
    for index in range(open_index, len(text)):
        char = text[index]
        if char == "{":
            depth += 1
        elif char == "}":
            depth -= 1
            if depth == 0:
                return index
    return -1


def main_context_shapes(text: str) -> dict[str, str]:
    start = text.find("export const MainContext")
    if start == -1:
        return {}
    open_brace = text.find("{", start)
    close_brace = match_braces(text, open_brace)
    body = text[open_brace:close_brace]
    shapes: dict[str, str] = {}
    for match in re.finditer(
            r"(?P<key>[A-Za-z_$][\w$]*)\s*:\s*createProxyIdentifier\s*<"
            r"(?P<iface>[A-Za-z_$][\w$]*)>", body):
        shapes[match.group("key")] = match.group("iface")
    return shapes


def split_top_level(text: str, separator: str) -> list[str]:
    parts: list[str] = []
    depth = 0
    current: list[str] = []
    for char in text:
        if char in "([{<":
            depth += 1
        elif char in ")]}>":
            depth -= 1
        if char == separator and depth == 0:
            parts.append("".join(current).strip())
            current = []
            continue
        current.append(char)
    tail = "".join(current).strip()
    if tail:
        parts.append(tail)
    return parts


def interface_members(text: str, name: str) -> list[tuple[str, str]]:
    """Returns the (method, return type) pairs of an interface."""
    match = re.search(rf"export\s+interface\s+{re.escape(name)}\b", text)
    if not match:
        return []
    open_brace = text.find("{", match.end())
    if open_brace == -1:
        return []
    close_brace = match_braces(text, open_brace)
    if close_brace == -1:
        return []
    body = text[open_brace + 1:close_brace]

    members: list[tuple[str, str]] = []
    for found in re.finditer(r"^\s*\$(?P<name>\w+)\s*\(", body, re.M):
        # The return type is what follows the closing parenthesis of the
        # argument list.
        open_paren = body.find("(", found.end() - 1)
        if open_paren == -1:
            continue
        depth = 0
        close_paren = -1
        for index in range(open_paren, len(body)):
            char = body[index]
            if char == "(":
                depth += 1
            elif char == ")":
                depth -= 1
                if depth == 0:
                    close_paren = index
                    break
        if close_paren == -1:
            continue
        rest = body[close_paren + 1:]
        line_end = rest.find("\n")
        if line_end != -1:
            rest = rest[:line_end]
        rest = rest.strip()
        if rest.startswith(":"):
            rest = rest[1:].strip()
        else:
            rest = "void"
        members.append((found.group("name"), rest.rstrip(";").strip()))
    return members


def classify(return_type: str) -> str:
    """Maps a declared return type onto the kind of benign answer."""
    text = return_type.replace("\n", " ").strip()

    # A promise: the answer is what the promise resolves to.
    promise = re.search(r"Promise\s*<(?P<inner>.*)>\s*$", text)
    if promise:
        inner = promise.group("inner").strip()
    else:
        inner = text

    # A union with `undefined` or `void` means "there may be nothing".
    if re.search(r"\bundefined\b", inner) or re.search(r"\bvoid\b", inner):
        # A string can still be empty, an array can still be empty.
        if re.search(r"\bstring\b", inner) and "[]" not in inner:
            return "EmptyString"
        if re.search(r"\[\]|Array<|ReadonlyArray<", inner):
            return "EmptyArray"
        return "Null"

    if re.search(r"\[\]|Array<|ReadonlyArray<", inner):
        return "EmptyArray"
    if inner == "string":
        return "EmptyString"
    if inner == "number":
        return "Zero"
    if inner == "boolean":
        return "False"
    return "Null"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="fail when the committed header is out of date")
    args = parser.parse_args()

    protocol = None
    for candidate in UPSTREAM_PROTOCOL_CANDIDATES:
        if candidate.exists():
            protocol = candidate
            break
    if protocol is None:
        print("[fallbacks] the upstream protocol file was not found", file=sys.stderr)
        return 1

    text = protocol.read_text(encoding="utf-8", errors="replace")
    shapes = main_context_shapes(text)
    if not shapes:
        print("[fallbacks] the MainContext registry was not found", file=sys.stderr)
        return 1

    entries: list[tuple[str, str]] = []
    for key in sorted(shapes):
        for method, return_type in interface_members(text, shapes[key]):
            entries.append((f"{key}.${method}", classify(return_type)))
    entries.sort()

    lines = [
        f'    {{ "{key}", FallbackKind::{kind} }},'
        for key, kind in entries
    ]
    rendered = HEADER_TEMPLATE.format(
        source_rel=str(protocol.relative_to(REPO_ROOT.parent)).replace("\\", "/"),
        entries="\n".join(lines),
        count=len(entries),
    )

    if args.check:
        current = HEADER_PATH.read_text(encoding="utf-8") if HEADER_PATH.exists() else ""
        if current != rendered:
            print("[fallbacks] the generated header is stale", file=sys.stderr)
            return 1
        print(f"[fallbacks] {len(entries)} entries, the header is up to date")
        return 0

    HEADER_PATH.parent.mkdir(parents=True, exist_ok=True)
    HEADER_PATH.write_text(rendered, encoding="utf-8", newline="\n")
    print(f"[fallbacks] wrote {HEADER_PATH.name} ({len(entries)} entries)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
