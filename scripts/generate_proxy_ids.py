#!/usr/bin/env python3
"""
Generates the VS Code RPC proxy identifier table used by Vrutti's C++ core.

WHY THIS EXISTS
---------------
VS Code's RPC layer addresses actors ("shapes") by a small integer `nid`
assigned in declaration order by `createProxyIdentifier()`:

    // src/vr/workbench/services/extensions/common/proxyIdentifier.ts
    export class ProxyIdentifier<T> {
        public static count = 0;
        public readonly nid: number;
        constructor(sid: string) {
            this.sid = sid;
            this.nid = (++ProxyIdentifier.count);   // <- 1-based
        }
    }

Every `createProxyIdentifier()` call in the whole VS Code tree lives in
`src/vr/workbench/api/common/extHost.protocol.ts`, and the `nid` is simply the
1-based index of the call in file order.

The Vrutti C++ core receives RPC traffic over the "VruttiJSONBridge" protocol
(see `src/vr/workbench/api/node/extensionHostProcess.ts`), where each request
carries `proxyId` (the `nid`) plus a bare `method` name (e.g. `$registerCommand`).
The method name alone is ambiguous across shapes, so the C++ side needs the
numeric `nid` to route a call to the right shape implementation.

This script parses the upstream protocol file and emits a committed C++ header
so that:
  * the mapping is never hand-maintained (no drift when VS Code is re-synced),
  * release builds do not require the VS Code source tree at compile time.

USAGE
-----
    python scripts/generate_proxy_ids.py [--vscode-root D:\\vrutti] [--check]

`--check` regenerates into memory and fails (exit 1) if the committed header is
stale -- suitable for CI.
"""

from __future__ import annotations

import argparse
import pathlib
import re
import sys

# Matches: createProxyIdentifier<SomeShape>('SomeSid')
PROXY_RE = re.compile(
    r"createProxyIdentifier\s*<[^>]*>\s*\(\s*'(?P<sid>[^']+)'\s*\)"
)

# Matches the key of an object-literal entry: `MainThreadCommands: createProxy...`
KEY_RE = re.compile(r"(?P<key>[A-Za-z_$][A-Za-z0-9_$]*)\s*:\s*createProxyIdentifier")

# The two registry objects we care about.
MAIN_CONTEXT_RE = re.compile(r"export\s+const\s+MainContext\s*=\s*\{")
EXT_CONTEXT_RE = re.compile(r"export\s+const\s+ExtHostContext\s*=\s*\{")

HEADER_TEMPLATE = """//------------------------------------------------------------------------------
// <auto-generated>
//   Generated by scripts/generate_proxy_ids.py -- DO NOT EDIT BY HAND.
//
//   Source of truth:
//     {source_rel}
//
//   VS Code assigns each RPC "shape" (actor) a 1-based integer `nid` in
//   declaration order. The VruttiJSONBridge wire protocol carries that integer
//   as `proxyId` alongside a bare method name, so the C++ router needs this
//   table to dispatch a call to the correct shape.
//
//   Regenerate with:
//     python scripts/generate_proxy_ids.py
// </auto-generated>
//------------------------------------------------------------------------------

#pragma once

namespace vrutti::core::ipc {{
namespace proxy {{

// --- MainContext: actors that live in the RENDERER and are called BY the ExtHost
namespace Main {{
{main_entries}
}}

// --- ExtHostContext: actors that live in the EXTENSION HOST and are called BY the renderer
namespace Ext {{
{ext_entries}
}}

// --- Lookup helpers -------------------------------------------------------------

// Returns the shape name for a numeric proxy id, or nullptr when unknown.
inline const char* shapeName(int nid) {{
    switch (nid) {{
{name_cases}
        default: return nullptr;
    }}
}}

// Returns the numeric proxy id for a shape name, or -1 when unknown.
inline int shapeId(const char* name) {{
    if (!name) return -1;
{id_cases}
    return -1;
}}

}} // namespace proxy
}} // namespace vrutti::core::ipc
"""


def parse_proxy_table(source_path: pathlib.Path) -> list[tuple[str, str, int]]:
    """Returns [(registry, key, nid), ...] in file order."""
    text = source_path.read_text(encoding="utf-8")

    main_at = MAIN_CONTEXT_RE.search(text)
    ext_at = EXT_CONTEXT_RE.search(text)
    if not main_at or not ext_at:
        raise SystemExit(
            f"error: could not locate MainContext / ExtHostContext in {source_path}"
        )

    # Pre-compute the object-literal keys so each proxy call can be matched
    # against the key that immediately precedes it.
    key_matches = list(KEY_RE.finditer(text))

    entries: list[tuple[str, str, int]] = []
    for match in PROXY_RE.finditer(text):
        sid = match.group("sid")

        # Find the object-literal key immediately preceding this call.
        key_match = None
        for candidate in key_matches:
            if candidate.start() < match.start():
                key_match = candidate
            else:
                break
        if key_match is None:
            raise SystemExit(f"error: could not determine key for proxy '{sid}'")
        key = key_match.group("key")

        registry = "Main" if match.start() < ext_at.start() else "Ext"
        entries.append((registry, key, len(entries) + 1))

    if not entries:
        raise SystemExit(f"error: no proxy identifiers found in {source_path}")

    # Sanity: both registries must be represented and Main must come first.
    registries = [e[0] for e in entries]
    if "Main" not in registries or "Ext" not in registries:
        raise SystemExit("error: expected both MainContext and ExtHostContext entries")

    first_ext = registries.index("Ext")
    if any(r == "Main" for r in registries[first_ext:]):
        raise SystemExit(
            "error: interleaved Main/Ext registries -- the nid assignment "
            "assumption no longer holds; update the generator."
        )

    return entries


def render(entries: list[tuple[str, str, int]], source_rel: str) -> str:
    main_entries = "\n".join(
        f"    constexpr int {key} = {nid};" for registry, key, nid in entries if registry == "Main"
    )
    ext_entries = "\n".join(
        f"    constexpr int {key} = {nid};" for registry, key, nid in entries if registry == "Ext"
    )

    name_cases = "\n".join(
        f"        case {nid}: return \"{key}\";" for _registry, key, nid in entries
    )

    id_cases = "\n".join(
        f'    if (name == "{key}") return {nid};' for _registry, key, nid in entries
    )

    return HEADER_TEMPLATE.format(
        source_rel=source_rel,
        main_entries=main_entries,
        ext_entries=ext_entries,
        name_cases=name_cases,
        id_cases=id_cases,
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--vscode-root",
        default=r"D:\vrutti",
        help="Root of the upstream VS Code source tree (read-only).",
    )
    parser.add_argument(
        "--out",
        default=None,
        help="Output header path (default: src/core/ipc/VsCodeProxyIds.generated.h)",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Fail if the committed header is out of date instead of writing it.",
    )
    args = parser.parse_args()

    repo_root = pathlib.Path(__file__).resolve().parent.parent
    vscode_root = pathlib.Path(args.vscode_root)

    source = vscode_root / "src" / "vr" / "workbench" / "api" / "common" / "extHost.protocol.ts"
    if not source.exists():
        print(f"error: upstream protocol file not found: {source}", file=sys.stderr)
        return 1

    out_path = (
        pathlib.Path(args.out)
        if args.out
        else repo_root / "src" / "core" / "ipc" / "VsCodeProxyIds.generated.h"
    )

    entries = parse_proxy_table(source)
    try:
        source_rel = str(source.relative_to(vscode_root)).replace("\\", "/")
    except ValueError:
        source_rel = source.name

    rendered = render(entries, source_rel)

    if args.check:
        if not out_path.exists():
            print(f"error: generated header missing: {out_path}", file=sys.stderr)
            return 1
        current = out_path.read_text(encoding="utf-8")
        if current != rendered:
            print(
                f"error: {out_path} is stale -- run scripts/generate_proxy_ids.py",
                file=sys.stderr,
            )
            return 1
        print(f"ok: {out_path.name} is up to date ({len(entries)} proxy ids)")
        return 0

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(rendered, encoding="utf-8", newline="\n")

    main_count = sum(1 for r, _, _ in entries if r == "Main")
    ext_count = sum(1 for r, _, _ in entries if r == "Ext")
    print(
        f"wrote {out_path} ({len(entries)} proxy ids: "
        f"{main_count} MainContext, {ext_count} ExtHostContext)"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
